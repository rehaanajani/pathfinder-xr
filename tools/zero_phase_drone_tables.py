"""Writes results/track3/zero_phase_drone.md from the raw rows in results/track3/zero_phase_drone/*.json."""
import json
from pathlib import Path

import numpy as np

D = Path(__file__).resolve().parents[1] / "results" / "track3" / "zero_phase_drone"
KEYS = [("ate_rmse_m", "ATE"), ("checkpoints_m", "checkpoints"), ("blind_mean_m", "blind 5 s"), ("dropout_m", "dropouts")]
HELD = {"euroc:MH_04_difficult", "euroc:MH_05_difficult", "euroc:V1_03_difficult", "euroc:V2_03_difficult",
        "tumvi:room5", "tumvi:room6"}
GROUPS = {"Machine Hall": lambda s: ":MH" in s, "Vicon rooms": lambda s: ":V" in s, "TUM-VI": lambda s: "tumvi" in s}


def table(rows, settings, part):
    out = ["| inputs | setting | " + " | ".join(k for _, k in KEYS) + " | Machine Hall ckpt / blind | Vicon ckpt / blind |",
           "|---|---|" + "---:|" * (len(KEYS) + 2)]
    for s in sorted({r["set"] for r in rows}, key=lambda x: (x != "s42_accel_first", x)):
        for name in settings:
            rr = [r for r in rows if r["set"] == s and r["setting"] == name and part(r["data"])]
            if not rr:
                continue
            g = lambda f, k: np.mean([r[k] for r in rr if f(r["data"])])
            out.append(f"| {s.split('_')[0]} | {name} | " + " | ".join(f"{np.mean([r[k] for r in rr]):.3f}" for k, _ in KEYS)
                       + f" | {g(GROUPS['Machine Hall'], 'checkpoints_m'):.2f} / {g(GROUPS['Machine Hall'], 'blind_mean_m'):.2f}"
                       + f" | {g(GROUPS['Vicon rooms'], 'checkpoints_m'):.2f} / {g(GROUPS['Vicon rooms'], 'blind_mean_m'):.2f} |")
    return "\n".join(out)


def main():
    sweep = json.loads((D / "sweep_dev.json").read_text())
    frozen = json.loads((D / "check_frozen.json").read_text())
    coast = json.loads((D / "check_coast_from_failure.json").read_text())
    names = list(dict.fromkeys(r["setting"] for r in sweep))
    md = f"""# Offline zero-phase pull on the drone mount

**Kept.** On the drone mount (rotor drag on), the causal pull of position back to the start is replaced, up to the
moment the IMU dies, by an offline zero-phase one: the un-pulled position minus its forward-backward low-pass, with a
time constant that shortens from 48 s to 12 s along the organisers' damage ramp (γ 1.7). The rows after the failure
keep the causal entry's positions, so the blind window is the entry's own. The FAQ allows non-causal processing.
Handheld and headset mounts are unchanged. Options: `--zp-tau-start 48 --zp-tau-end 12` (`0` turns it off).

Inputs: the organisers' `degrade_imu.py`, accel-first, from `tools/competitor_scoreboard.py inputs`. Settings were
chosen on the 11 development recordings at seed 42; the 6 held-out recordings and seeds 1 and 7 were then checked.
Tables are generated by `tools/zero_phase_drone_tables.py` from the raw JSON in `zero_phase_drone/`.

## All 17 recordings (mean metres)

{table(frozen, ["entry", "zpb 48->12 keep"], lambda s: True)}

## Held-out recordings only

{table(frozen, ["entry", "zpb 48->12 keep"], lambda s: s in HELD)}

## Smoothing straight through the failure, or coasting from the smoothed point

Smoothing through the dead-sensor rows, or continuing the blind window from the smoothed position, made blind worse
on held-out recordings and fresh seeds; keeping the entry's own blind rows fixes that.

{table(coast, ["entry", "zpb 48->12 off"], lambda s: True)}

## Development sweep (seed 42, 11 recordings)

`zp A->B`: smoothed through the whole file; `zpb A->B entry|off|keep`: smoothed up to the failure, then the blind rows
continue the causal entry's motion, the un-pulled motion, or are the causal entry's own positions.

{table(sweep, names, lambda s: True)}

## Trade-off

V1_03 (a held-out Vicon recording) gets worse by about 0.2 m on checkpoints and dropouts and is then no better than
standing still on those windows; every group mean improves.
"""
    (D.parent / "zero_phase_drone.md").write_text(md)


if __name__ == "__main__":
    main()
