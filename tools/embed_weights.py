"""Embeds the network weights in src/main.py, so main.py runs on its own.

    python tools/embed_weights.py            # rewrites the EMBEDDED_WEIGHTS block from src/velnet_weights*.bin

The weights are stored zlib-compressed and base64-encoded; main.py decodes them to the same bytes as the files.
"""
import base64
import re
import zlib
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "src"
START = "# ---- embedded weights (generated by tools/embed_weights.py from src/velnet_weights*.bin; zlib + base64) ----"
END = "# ---- end of embedded weights ----"


def block():
    out = [START, "EMBEDDED_WEIGHTS = {"]
    for key, name in (("body", "velnet_weights.bin"), ("world", "velnet_weights_world.bin")):
        enc = base64.b64encode(zlib.compress((SRC / name).read_bytes(), 9)).decode("ascii")
        # One literal per weight set: compiling thousands of joined pieces costs several MB of peak memory.
        out.append(f'    "{key}": "{enc}",  # {name}')
    out += ["}", END]
    return "\n".join(out)


def main():
    p = SRC / "main.py"
    t = p.read_text()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block(), t, count=1, flags=re.S)
    if new == t and START not in t:
        raise SystemExit("markers not found in src/main.py")
    p.write_text(new)
    print(f"embedded weights in {p} ({p.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
